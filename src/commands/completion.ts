import { Command, Option } from 'commander';

/**
 * `autohisab-business completion [shell]` — print a tab-completion script for
 * zsh, bash or powershell to stdout. The script is generated dynamically by
 * walking the commander program tree (commands, options, arguments), so it
 * never drifts when commands or flags are added.
 *
 * When [shell] is omitted the current shell is auto-detected from $SHELL
 * (Unix) or defaults to powershell on Windows. The script itself is kept
 * clean on stdout so it stays eval-able; setup guidance goes to stderr via
 * --instructions (or automatically when stdout is a TTY).
 */

const SUPPORTED_SHELLS = ['zsh', 'bash', 'powershell'] as const;
type Shell = (typeof SUPPORTED_SHELLS)[number];

/** Per-option value enums for the few options with a fixed value set. */
const OPTION_VALUES: Record<string, Record<string, string[]>> = {
  deploy: { '--target': ['platform', 'vercel', 'self'] },
  init: { '--template': ['next-js', 'php-remote'] },
};

interface OptionInfo {
  long: string | undefined;
  short: string | undefined;
  description: string;
  takesValue: boolean;
  values?: string[];
}

interface CommandInfo {
  name: string;
  description: string;
  options: OptionInfo[];
}

function collectCommands(program: Command): CommandInfo[] {
  const globalOptions: OptionInfo[] = [
    ...program.options.map((o) => optionInfo('', o)),
    { long: '--help', short: '-h', description: 'display help for command', takesValue: false },
  ];
  return program.commands.map((cmd) => ({
    name: cmd.name(),
    description: cmd.description(),
    options: [
      ...cmd.options.map((o) => optionInfo(cmd.name(), o)),
      ...globalOptions,
    ],
  }));
}

function optionInfo(cmdName: string, o: Option): OptionInfo {
  const long = o.long;
  return {
    long,
    short: o.short,
    description: o.description || '',
    takesValue: /<|\[/.test(o.flags),
    values: long ? OPTION_VALUES[cmdName]?.[long] : undefined,
  };
}

/** Strip characters that would break shell quoting in descriptions. */
function clean(s: string): string {
  return s.replace(/['"`\\[\]:]/g, ' ').replace(/\s+/g, ' ').trim();
}

/**
 * Detect the current shell: basename of $SHELL on Unix (e.g. /bin/zsh → zsh),
 * powershell on Windows. Throws with a helpful message when unknown.
 */
export function detectShell(
  env: NodeJS.ProcessEnv = process.env,
  platform: NodeJS.Platform = process.platform,
): Shell {
  if (platform === 'win32') return 'powershell';
  const shellPath = env.SHELL ?? '';
  const base = shellPath.split('/').pop() ?? '';
  if ((SUPPORTED_SHELLS as readonly string[]).includes(base)) return base as Shell;
  throw new Error(
    `Could not detect your shell (SHELL="${shellPath || 'unset'}"). ` +
      `Pass one explicitly: autohisab-business completion <${SUPPORTED_SHELLS.join('|')}>`,
  );
}

function renderZsh(program: Command): string {
  const cmds = collectCommands(program);
  const lines: string[] = [
    '#compdef autohisab-business',
    '# zsh completion for autohisab-business — generated by `autohisab-business completion zsh`',
    '_autohisab_business() {',
    '  local -a _cmds',
    '  _cmds=(',
    ...cmds.map((c) => `    '${c.name}:${clean(c.description)}'`),
    '  )',
    '  if (( CURRENT == 2 )); then',
    "    _describe -t commands 'autohisab-business command' _cmds",
    '    return',
    '  fi',
    '  case ${words[2]} in',
  ];
  for (const c of cmds) {
    lines.push(`    ${c.name})`);
    lines.push('      _arguments \\');
    const specs: string[] = [];
    for (const o of c.options) {
      const desc = clean(o.description);
      const names = o.short ? [o.short, o.long!] : [o.long!];
      for (const n of names) {
        const valueSpec = o.takesValue
          ? o.values
            ? `:value:(${o.values.join(' ')})`
            : ':value:'
          : '';
        specs.push(`'${n}[${desc}]${valueSpec}'`);
      }
    }
    specs.forEach((s, i) => {
      lines.push(`        ${s}${i < specs.length - 1 ? ' \\' : ''}`);
    });
    lines.push('      ;;');
  }
  lines.push('  esac', '}', '_autohisab_business "$@"');
  return lines.join('\n') + '\n';
}

function renderBash(program: Command): string {
  const cmds = collectCommands(program);
  const lines: string[] = [
    '# bash completion for autohisab-business — generated by `autohisab-business completion bash`',
    '_autohisab_business() {',
    '  local cur prev cmd',
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
    '  cmd="${COMP_WORDS[1]}"',
    '',
    '  if (( COMP_CWORD == 1 )); then',
    `    COMPREPLY=( $(compgen -W "${cmds.map((c) => c.name).join(' ')}" -- "$cur") )`,
    '    return 0',
    '  fi',
    '',
    '  # Value completion for options with a fixed value set.',
    '  case "$prev" in',
  ];
  const seen = new Set<string>();
  for (const c of cmds) {
    for (const o of c.options) {
      if (!o.values) continue;
      for (const n of [o.short, o.long].filter(Boolean) as string[]) {
        if (seen.has(n)) continue;
        seen.add(n);
        lines.push(`    ${n}) COMPREPLY=( $(compgen -W "${o.values.join(' ')}" -- "$cur") ); return 0 ;;`);
      }
    }
  }
  lines.push('  esac', '', '  if [[ "$cur" == -* ]]; then', '    case "$cmd" in');
  for (const c of cmds) {
    const words = c.options.flatMap((o) => (o.short ? [o.short, o.long!] : [o.long!]));
    lines.push(`      ${c.name}) COMPREPLY=( $(compgen -W "${words.join(' ')}" -- "$cur") ) ;;`);
  }
  lines.push('    esac', '  fi', '  return 0', '}', 'complete -F _autohisab_business autohisab-business');
  return lines.join('\n') + '\n';
}

function renderPowerShell(program: Command): string {
  const cmds = collectCommands(program);
  const commandNames = cmds.map((c) => `'${c.name}'`).join(', ');
  const lines: string[] = [
    '# PowerShell completion for autohisab-business — generated by `autohisab-business completion powershell`',
    'Register-ArgumentCompleter -Native -CommandName autohisab-business -ScriptBlock {',
    '  param($wordToComplete, $commandAst, $cursorPosition)',
    '  $words = $commandAst.ToString() -split "\\s+"',
    '  # Words after the executable name; index of the word being completed.',
    '  $tail = $words | Select-Object -Skip 1',
    '  $idx = $tail.Count - 1',
    '  if ($wordToComplete -eq "" -or $cursorPosition -gt ($commandAst.ToString().Length)) { $idx += 1 }',
    '',
    '  $commands = @(' + commandNames + ')',
    '',
    '  $options = @{',
  ];
  for (const c of cmds) {
    const words = c.options.flatMap((o) => (o.short ? [o.short, o.long!] : [o.long!]));
    lines.push(`    '${c.name}' = @(${words.map((w) => `'${w}'`).join(', ')})`);
  }
  lines.push('  }', '', '  $optionValues = @{');
  const seen = new Set<string>();
  for (const c of cmds) {
    for (const o of c.options) {
      if (!o.values || !o.long || seen.has(o.long)) continue;
      seen.add(o.long);
      lines.push(`    '${o.long}' = @(${o.values.map((v) => `'${v}'`).join(', ')})`);
    }
  }
  lines.push(
    '  }',
    '',
    '  # Completing the value of an enum option (previous word is the option).',
    '  if ($idx -ge 1) {',
    '    $prev = $tail[$idx - 1]',
    '    if ($optionValues.ContainsKey($prev)) {',
    '      $optionValues[$prev] | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {',
    '        [System.Management.Automation.CompletionResult]::new($_, $_, "ParameterValue", $_)',
    '      }',
    '      return',
    '    }',
    '  }',
    '',
    '  # First word after the executable: complete command names.',
    '  if ($idx -le 0) {',
    '    $commands | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {',
    '      [System.Management.Automation.CompletionResult]::new($_, $_, "Command", $_)',
    '    }',
    '    return',
    '  }',
    '',
    '  # Complete --options for the given subcommand.',
    '  if ($wordToComplete -like "-*") {',
    '    $cmd = $tail[0]',
    '    if ($options.ContainsKey($cmd)) {',
    '      $options[$cmd] | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {',
    '        [System.Management.Automation.CompletionResult]::new($_, $_, "ParameterName", $_)',
    '      }',
    '    }',
    '  }',
    '}',
  );
  return lines.join('\n') + '\n';
}

/** Render the completion script for `shell`; throws on unsupported shells. */
export function renderCompletion(program: Command, shell: string): string {
  if (shell === 'zsh') return renderZsh(program);
  if (shell === 'bash') return renderBash(program);
  if (shell === 'powershell') return renderPowerShell(program);
  throw new Error(
    `Unsupported shell "${shell}". Supported: ${SUPPORTED_SHELLS.join(', ')}.`,
  );
}

/** Setup guidance, printed to stderr (never stdout — the script stays eval-able). */
export function setupInstructions(shell: Shell): string {
  switch (shell) {
    case 'zsh':
      return [
        'zsh (Warp, iTerm, Terminal — all read ~/.zshrc):',
        '  echo \'eval "$(autohisab-business completion zsh)"\' >> ~/.zshrc',
        '  # Must come AFTER any `compinit` call in ~/.zshrc. If there is none,',
        '  # add this line BEFORE it:  autoload -Uz compinit && compinit',
        '  source ~/.zshrc   # or restart the shell',
      ].join('\n');
    case 'bash':
      return [
        'bash:',
        '  macOS (Homebrew bash-completion):',
        '    autohisab-business completion bash > "$(brew --prefix)/etc/bash_completion.d/autohisab-business"',
        '  Linux / Git Bash on Windows:',
        "    echo 'source <(autohisab-business completion bash)' >> ~/.bashrc",
        '  source ~/.bashrc   # or restart the shell',
      ].join('\n');
    case 'powershell':
      return [
        'PowerShell (Windows / pwsh):',
        '  autohisab-business completion powershell >> $PROFILE',
        '  . $PROFILE   # or restart the shell',
      ].join('\n');
  }
}

export function makeCompletionCommand(program: Command): Command {
  return new Command('completion')
    .description(
      'Print a shell tab-completion script (zsh | bash | powershell; auto-detected when omitted).',
    )
    .argument('[shell]', 'Shell to generate for: zsh | bash | powershell')
    .option('--instructions', 'Print setup guidance for the detected shell to stderr')
    .action((shellArg: string | undefined, opts: { instructions?: boolean }) => {
      const shell = shellArg ?? detectShell();
      if (!(SUPPORTED_SHELLS as readonly string[]).includes(shell)) {
        throw new Error(
          `Unsupported shell "${shell}". Supported: ${SUPPORTED_SHELLS.join(', ')}.`,
        );
      }
      process.stdout.write(renderCompletion(program, shell));
      if (opts.instructions || process.stdout.isTTY) {
        process.stderr.write(`\n# Setup — ${setupInstructions(shell as Shell)}\n`);
      }
    });
}
