#!/usr/bin/env node
/**
 * Regenerates `assets/icon-vocabulary.json` — the icon vocabulary `doctor`'s
 * `manifest-icons` rule and `push`'s icon warning check validate `icon`
 * fields against (PG-333).
 *
 * The CLI is a separate repo/package from the host (flashmandu/chiya-shots),
 * so it cannot derive the vocabulary at RUNTIME the way the host's
 * `IconVocabulary` (packages/flashmandu/apps/src/Support/IconVocabulary.php)
 * globs `vendor/livewire/flux/stubs/resources/views/flux/icon` — there is no
 * such directory inside this package. Instead this script is the offline
 * equivalent: point it at a checkout of the host (or any directory holding
 * Flux `icon/*.blade.php` files) and it writes the SAME derivation — icon
 * names, never a hand-written list — as a committed JSON asset the CLI ships.
 *
 * Usage:
 *   node scripts/generate-icon-vocabulary.mjs [pathToHostFluxIconDir]
 *
 * Defaults to the sibling host checkout's vendored Flux stubs
 * (~/Herd/chiya-shots/vendor/livewire/flux/stubs/resources/views/flux/icon),
 * matching the platform knowledge plugin's PLATFORM_KIT_DIR convention
 * (default ~/Herd) for "the other repo lives next to this one".
 *
 * Re-run this after a Flux upgrade lands on the host (`composer update
 * livewire/flux`) — the committed asset is a snapshot, not a live read, so it
 * only tracks the host's icon set at the moment someone regenerates it. A
 * test (`icon-vocabulary.test.ts`) only asserts the asset is well-formed and
 * non-empty, not that it is current — staleness is caught by `doctor`
 * accepting/rejecting real icon names during ordinary use, the same way a
 * stale `KIT_OWNED_FILES` hash list is caught by `kit-current`.
 */

import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

const defaultHostIconDir = path.join(
  os.homedir(),
  'Herd',
  'chiya-shots',
  'vendor',
  'livewire',
  'flux',
  'stubs',
  'resources',
  'views',
  'flux',
  'icon',
);

const iconDir = process.argv[2] ?? defaultHostIconDir;

if (!existsSync(iconDir)) {
  console.error(`No Flux icon directory at ${iconDir}. Pass one explicitly:`);
  console.error('  node scripts/generate-icon-vocabulary.mjs <path-to-flux-icon-dir>');
  process.exit(1);
}

const names = readdirSync(iconDir)
  .filter((f) => f.endsWith('.blade.php'))
  .map((f) => f.slice(0, -'.blade.php'.length))
  .sort();

if (names.length === 0) {
  console.error(`Found zero *.blade.php files under ${iconDir} — refusing to write an empty vocabulary.`);
  process.exit(1);
}

const outDir = path.join(repoRoot, 'assets');
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

const outFile = path.join(outDir, 'icon-vocabulary.json');
writeFileSync(
  outFile,
  JSON.stringify(
    {
      $comment:
        'Generated by scripts/generate-icon-vocabulary.mjs from the installed Flux icon set. ' +
        'Do not hand-edit — re-run the script after a Flux upgrade lands on the host.',
      source: iconDir,
      generatedAt: new Date().toISOString(),
      icons: names,
    },
    null,
    2,
  ) + '\n',
);

console.log(`Wrote ${names.length} icon names to ${path.relative(repoRoot, outFile)} (source: ${iconDir})`);
